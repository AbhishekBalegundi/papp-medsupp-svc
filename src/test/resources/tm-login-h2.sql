-- The CARTMAN tables the tests need, carrying the Delphi column names verbatim.
-- Only the columns the entities map are present; the real TM_Login has 130.
--
-- The names here are deliberately spelled the way SQL Server spells them, including the odd
-- casing of LOg_System. If Hibernate's physical naming strategy ever starts rewriting explicit
-- @Column names again, these queries stop resolving — which is the point of the file.
--
-- TenCharUsr, LockedUser and DisabledUs are exactly 10 characters on purpose: H2, unlike SQL
-- Server and PostgreSQL, does not ignore char(10) padding when comparing, so a lookup by name
-- only matches on H2 when the name fills the column. HTTP-level tests must use those.

